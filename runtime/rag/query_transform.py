"""查询改写：受控的领域词表扩展。

为什么不是"让 LLM 改写 3 个 query"：
  - 每次问答多 1 次模型调用（500~1500ms + 成本），且改写本身可能引入幻觉意图；
  - 企业知识库的高频查询集中在有限术语上，一张受控的同义词表
    （等价于 Elasticsearch 的 synonym graph）在离线、零成本的前提下更可控。

为什么也不做伪相关反馈（RM3）：
  试过一版"取首轮 top-3 文档的高 IDF 词补充查询"，结果是查询漂移——
  语料外问题（"公司有没有太空电梯补贴"）靠"公司/有没有"误召回一篇年假制度，
  反馈词全部来自该文档，重排覆盖率刷到 1.0，噪声被当成满分证据。
  这类问题必须用"扩展词来自受控词表"来约束，调阈值救不回来。

实现约束：
  1. 只扩展词面（BM25），不额外调用 embedding；
  2. 词表是企业通用语汇，不含任何租户数据，可以随代码发布；
  3. 扩展不改变路由意图，只影响召回候选。
"""
