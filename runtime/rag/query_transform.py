def lexicon_terms(query: str, *, limit: int = 5) -> list[str]:
    expansions: list[str] = []
    for trigger, terms in _DOMAIN_LEXICON.items():
        if trigger in query:
            for term in terms:
                if term not in query and term not in expansions:
                    expansions.append(term)
    return expansions[:limit]


def expand_queries(query: str, *, max_variants: int = 3) -> list[str]:
    """返回 [原查询, 词表扩展]。没命中词表就原样返回（绝不臆造扩展）。"""
    variants = [query]
    synonyms = lexicon_terms(query)
    if synonyms:
        variants.append(f"{query} {' '.join(synonyms)}")

    deduped: list[str] = []
    for item in variants:
        if item not in deduped:
            deduped.append(item)
    return deduped[: max(1, max_variants)]
